#!/usr/bin/env python3
"""
tools/cinco/gen_sprites.py
Converts SCUMM/LucasArts-style sprite frames from assets/scumm_sprites/ into
compact 4-bit RLE C arrays in firmware/src/cinco_assets.h.
"""

import os
import sys

try:
    from PIL import Image
except ImportError:
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    venv_py = os.path.join(base_dir, ".venv", "bin", "python3")
    if os.path.exists(venv_py) and sys.executable != venv_py:
        os.execv(venv_py, [venv_py] + sys.argv)
    raise

def rgb888_to_rgb565(r, g, b):
    # Native 16-bit RGB565: 5 bits red, 6 bits green, 5 bits blue
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def encode_animation(anim_name, frame_paths, fps=10):
    images = [Image.open(p).convert("RGB") for p in frame_paths]
    w, h = images[0].size
    nframes = len(images)
    
    # 1. Unified 16-color palette
    filmstrip = Image.new("RGB", (w * nframes, h))
    for i, im in enumerate(images):
        filmstrip.paste(im, (i * w, 0))
    filmstrip_p = filmstrip.quantize(colors=16, dither=Image.NONE)
    raw_pal = filmstrip_p.getpalette() or []
    if len(raw_pal) < 48:
        raw_pal = raw_pal + [255] * (48 - len(raw_pal))
    raw_pal = raw_pal[:48]
    
    pal565 = []
    for c in range(16):
        r, g, b = raw_pal[c * 3 : c * 3 + 3]
        pal565.append(rgb888_to_rgb565(r, g, b))
        
    pal_img = Image.new("P", (1, 1))
    pal_img.putpalette(raw_pal + [0] * (768 - len(raw_pal)))
    
    # 2. RLE encode each frame
    frame_offsets = []
    rle_data = bytearray()
    
    for im in images:
        frame_offsets.append(len(rle_data))
        im_p = im.quantize(palette=pal_img, dither=Image.NONE)
        pixels = list(im_p.getdata())
        
        i = 0
        while i < len(pixels):
            color = pixels[i] & 0x0F
            run = 1
            while (i + run < len(pixels)) and ((pixels[i + run] & 0x0F) == color) and (run < 16):
                run += 1
            rle_data.append(((run - 1) << 4) | color)
            i += run
            
    return {
        "name": anim_name,
        "w": w,
        "h": h,
        "nframes": nframes,
        "fps": fps,
        "pal": pal565,
        "frame_offsets": frame_offsets,
        "rle": rle_data
    }

def main():
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    src_dir = os.path.join(base_dir, "assets", "scumm_sprites")
    out_header = os.path.join(base_dir, "firmware", "src", "cinco_assets.h")
    
    # Extract frames from loops or frame sequences
    anim_defs = [
        ("celery", "celery_scumm_loop.gif", 8),
        ("tayne", "tayne_scumm_loop.gif", 8),
        ("tayne_hatwobble", "tayne_hatwobble_scumm_loop.gif", 10),
        ("tayne_flarh", "tayne_flarh_scumm_loop.gif", 12),
        ("oyster", "oyster_scumm_loop.gif", 6),
    ]
    
    encoded_anims = []
    total_bytes = 0
    
    for name, gif_file, fps in anim_defs:
        gif_path = os.path.join(src_dir, gif_file)
        if not os.path.exists(gif_path):
            print(f"Skipping {name}: {gif_path} not found")
            continue
        im = Image.open(gif_path)
        frames = []
        for f in range(getattr(im, "n_frames", 1)):
            im.seek(f)
            tmp_f = im.convert("RGB")
            frames.append(tmp_f)
            
        # Write frames to temp files for encoder
        tmp_paths = []
        for i, frame in enumerate(frames):
            tp = os.path.join(src_dir, f"tmp_{name}_{i}.png")
            frame.save(tp)
            tmp_paths.append(tp)
            
        enc = encode_animation(name, tmp_paths, fps=fps)
        encoded_anims.append(enc)
        total_bytes += len(enc["rle"]) + 32 + len(enc["frame_offsets"]) * 4
        print(f"Encoded {name:16s}: {enc['w']}x{enc['h']}, {enc['nframes']} frames -> {len(enc['rle'])} bytes RLE")
        
        for tp in tmp_paths:
            os.remove(tp)
            
    print(f"\nTotal Compressed Sprite Storage: {total_bytes} bytes ({total_bytes / 1024:.1f} KB)")
    
    # Write C header
    with open(out_header, "w") as fp:
        fp.write("/* SPDX-License-Identifier: GPL-3.0-only\n")
        fp.write(" * Copyright (C) 2026 Cinco Identity Generator 2.5 / Celery Man Firmware */\n")
        fp.write("/* Generated by tools/cinco/gen_sprites.py - DO NOT EDIT MANUALLY */\n\n")
        fp.write("#ifndef CINCO_ASSETS_H\n#define CINCO_ASSETS_H\n\n#include <stdint.h>\n\n")
        fp.write("typedef struct {\n")
        fp.write("    uint8_t w;\n    uint8_t h;\n    uint8_t nframes;\n    uint8_t fps;\n")
        fp.write("    const uint16_t *pal;\n")
        fp.write("    const uint32_t *frame_off;\n")
        fp.write("    const uint8_t *rle;\n")
        fp.write("} cinco_anim_t;\n\n")
        
        for a in encoded_anims:
            name = a["name"]
            # Palette
            fp.write(f"static const uint16_t cinco_pal_{name}[16] = {{\n    ")
            for idx, p in enumerate(a["pal"]):
                fp.write(f"0x{p:04X}u, ")
                if (idx + 1) % 8 == 0:
                    fp.write("\n    ")
            fp.write("};\n\n")
            
            # Offsets
            fp.write(f"static const uint32_t cinco_off_{name}[{a['nframes']}] = {{\n    ")
            for idx, off in enumerate(a["frame_offsets"]):
                fp.write(f"{off}u, ")
            fp.write("\n};\n\n")
            
            # RLE data
            fp.write(f"static const uint8_t cinco_rle_{name}[{len(a['rle'])}] = {{\n    ")
            for idx, b in enumerate(a["rle"]):
                fp.write(f"0x{b:02X}u, ")
                if (idx + 1) % 16 == 0:
                    fp.write("\n    ")
            fp.write("\n};\n\n")
            
            # Struct definition
            fp.write(f"static const cinco_anim_t cinco_anim_{name} = {{\n")
            fp.write(f"    .w = {a['w']},\n    .h = {a['h']},\n    .nframes = {a['nframes']},\n    .fps = {a['fps']},\n")
            fp.write(f"    .pal = cinco_pal_{name},\n")
            fp.write(f"    .frame_off = cinco_off_{name},\n")
            fp.write(f"    .rle = cinco_rle_{name}\n")
            fp.write("};\n\n")
            
        fp.write("#endif /* CINCO_ASSETS_H */\n")
        
    print(f"Generated {out_header} successfully.")

if __name__ == "__main__":
    main()
